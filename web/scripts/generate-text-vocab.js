import fs from 'fs';
import path from 'path';

const TEXTS_DIR = 'static/texts';
const CORE_LISTS_DIR = 'static/core_lists';
const DICTIONARIES_DIR = 'static/dictionaries';
const OUTPUT_DIR = 'static/text-vocab';
const INDEX_FILE = path.join(TEXTS_DIR, 'index.json');

if (!fs.existsSync(OUTPUT_DIR)) {
	fs.mkdirSync(OUTPUT_DIR, { recursive: true });
}

function stripMacrons(word) {
	return word.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

function expandHeadword(raw) {
	const words = raw.split(/[\s,;–—/]+/).filter(Boolean);
	const result = new Set();
	for (const w of words) {
		const lower = w.toLowerCase();
		result.add(lower);
		const stripped = stripMacrons(lower);
		if (stripped !== lower) {
			result.add(stripped);
		}
		// also add with macrons removed and decomposed combining marks removed
	}
	return result;
}

function loadCoreList(lang) {
	const filePath = path.join(CORE_LISTS_DIR, `${lang}-core-list.csv`);
	const content = fs.readFileSync(filePath, 'utf-8');
	const lines = content.trim().split('\n');
	const core = new Set();
	for (let i = 1; i < lines.length; i++) {
		const line = lines[i];
		const match = line.match(/^"([^"]+)"/);
		const headword = match ? match[1] : line.split(',')[0];
		const expanded = expandHeadword(headword);
		for (const w of expanded) {
			core.add(w);
		}
	}
	return core;
}

function loadDictionary(lang) {
	const filePath = path.join(DICTIONARIES_DIR, `${lang}.json`);
	if (!fs.existsSync(filePath)) {
		return {};
	}
	return JSON.parse(fs.readFileSync(filePath, 'utf-8'));
}

function getSlug(filePath) {
	const basename = path.basename(filePath, '.annotated.json');
	return basename;
}

function generateTextVocab() {
	const index = JSON.parse(fs.readFileSync(INDEX_FILE, 'utf-8'));

	const coreLists = {
		latin: loadCoreList('latin'),
		greek: loadCoreList('greek')
	};

	const dictionaries = {
		latin: loadDictionary('latin'),
		greek: loadDictionary('greek')
	};

	const vocabIndex = [];

	for (const textInfo of index) {
		const lang = textInfo.language;
		const filePath = path.join('static', textInfo.path.replace('/shark-reader/', ''));
		if (!fs.existsSync(filePath)) {
			console.warn(`File not found: ${filePath}`);
			continue;
		}

		const textData = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
		const tokens = textData.tokens;
		const coreSet = coreLists[lang];
		const dictionary = dictionaries[lang];

		const lemmaCounts = new Map();

		for (const token of tokens) {
			if (token.t === 'w' && token.l) {
				const lemma = token.l;
				lemmaCounts.set(lemma, (lemmaCounts.get(lemma) || 0) + 1);
			}
		}

		const core = [];
		const nonCoreLemmas = [];

		for (const [lemma, count] of lemmaCounts) {
			if (coreSet.has(lemma.toLowerCase())) {
				core.push({ lemma, count });
			} else {
				nonCoreLemmas.push({ lemma, count });
			}
		}

		core.sort((a, b) => b.count - a.count);

		const hapax = nonCoreLemmas
			.filter(e => e.count === 1)
			.map(e => e.lemma)
			.sort();

		const nonHapax = nonCoreLemmas
			.filter(e => e.count > 1)
			.sort((a, b) => b.count - a.count);

		const n = nonHapax.length;
		const tertileSize = Math.ceil(n / 3);

		const frequent = nonHapax.slice(0, tertileSize);
		const medium = nonHapax.slice(tertileSize, tertileSize * 2);
		const rare = nonHapax.slice(tertileSize * 2);

		const result = {
			title: textInfo.title,
			author: textInfo.author,
			language: lang,
			workType: textInfo.work_type,
			categories: {
				core,
				frequent,
				medium,
				rare,
				hapax
			}
		};

		const slug = getSlug(filePath);
		vocabIndex.push({ slug, ...textInfo });

		const outputPath = path.join(OUTPUT_DIR, `${slug}.vocab.json`);
		fs.writeFileSync(outputPath, JSON.stringify(result));
		console.log(`Generated vocab for ${slug}: ${core.length} core, ${frequent.length} frequent, ${medium.length} medium, ${rare.length} rare, ${hapax.length} hapax`);
	}

	fs.writeFileSync(
		path.join(OUTPUT_DIR, 'index.json'),
		JSON.stringify(vocabIndex)
	);

	const tsSlugs = vocabIndex.map(i => `\t'${i.slug}'`).join(',\n');
	const tsContent = `// Auto-generated by generate-text-vocab.js\nexport const vocabSlugs: string[] = [\n${tsSlugs}\n];\n`;
	fs.writeFileSync(path.join('src', 'lib', 'generated', 'vocab-slugs.ts'), tsContent);

	console.log(`Generated vocab index with ${vocabIndex.length} texts`);
}

generateTextVocab();